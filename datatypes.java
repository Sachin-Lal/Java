public class datatypes {
    public static void main(String[] args) {
    // Numeric Data Types

    byte b= -12;// Range of byte-128 to 127
    System.out.println(b);
    short s = 32700;// Range of short-32768 to 32767
    System.out.println(s);
    int i = 1234; // Range of int -2,147,483,648 to 2,147,483,647
    System.out.println(i); 
    long l= 543254325; //Range of long  -9,223,372,036,854,775,808 to 9,223,372,036,854,775,807
    System.out.println(l); 
    
    // Floating Numeric Data Types
    
    float f = 342.63f;
    System.out.println(f);
    double d = 324.234242134;
    System.out.println(d);

    // Charecter Data Type

    char c1='a', c2='9', c3='^', c4='$';
    System.out.print(c1+" "+c2+" "+c3+" "+c4+" ");
    String st="Hello, I am learning Java.";
    System.out.println(st);

    // Boolean Data Type
    boolean bl=false;
    System.out.println(bl);

}
    
}
